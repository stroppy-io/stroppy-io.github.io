#!/usr/bin/env node
// Regenerates docs/changelog.md (the "Next" version page) from stroppy's
// CHANGELOG.md: full history including the Unreleased section.
// Source defaults to stroppy main tip; override with CHANGELOG_SOURCE.
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, resolve} from 'node:path';
import {loadSource, parseSections, renderSection, FRONTMATTER, DEFAULT_SOURCE} from './lib-changelog.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(root, 'docs/changelog.md');
// Relative links in stroppy's changelog point into stroppy's repository, not
// this site; they go to the file on GitHub at main, which is what Next tracks.
const REPO_BLOB = 'https://github.com/stroppy-io/stroppy/blob/main/';
const absolutize = (md) => md.replace(/\]\((?![a-z][a-z0-9+.-]*:|#|\/)([^)\s]+)\)/gi, (_, path) => `](${REPO_BLOB}${path.replace(/^\.\//, '')})`);

const sections = parseSections(await loadSource(DEFAULT_SOURCE));
if (!sections.length) throw new Error(`no changelog sections parsed from ${DEFAULT_SOURCE}`);

const out =
  FRONTMATTER('Changelog', 'User-facing changes across Stroppy releases.') +
  '\n{/* GENERATED by scripts/sync-changelog.mjs — do not edit by hand. */}\n\n' +
  absolutize(sections.map(renderSection).join('\n'));

writeFileSync(OUT, out);
console.log(`sync-changelog: wrote ${OUT} (${sections.length} sections) from ${DEFAULT_SOURCE}`);
